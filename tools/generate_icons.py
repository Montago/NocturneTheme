"""Builds the Nocturne icon set from icons/icons.json and the SVG files in icons/mdi/. Enum names are
the MDI names in PascalCase, as in MahApps' IconBrowser (view-grid -> ViewGrid):

    src/Nocturne.Wpf/Controls/NocturneIconKind.g.cs        enum + path data for <nc:NocturneIcon Kind="..." />
    src/Nocturne.Avalonia/Controls/NocturneIconKind.g.cs   the same for Nocturne.Avalonia
    src/Nocturne.Web/TagHelpers/NocturneIconKind.g.cs      the same enum for <nc-icon kind="..." />
    src/Nocturne.Web/wwwroot/img/icons.svg                 SVG sprite: one <symbol> per icon (id = MDI name), and
                                                           the theme's line icons (Styles/Icons.xaml) as stroke-<name>

The icons are Material Design Icons (Apache License 2.0, see icons/LICENSE), the same set as the
JetPack theme uses. They are kept in the repository, so building needs no network; --fetch downloads
the ones the manifest lists but the folder lacks, at the pinned package version.

Usage (from the repository root):
    python tools/generate_icons.py            write the file
    python tools/generate_icons.py --fetch    download missing SVGs first, then write
    python tools/generate_icons.py --check    exit with 1 when the file is out of date
"""
import json
import re
import os
import sys
import urllib.request
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ICONS = os.path.join(ROOT, 'icons')
SVG_DIR = os.path.join(ICONS, 'mdi')
OUT_WPF = os.path.join(ROOT, 'src', 'Nocturne.Wpf', 'Controls', 'NocturneIconKind.g.cs')
OUT_AVALONIA = os.path.join(ROOT, 'src', 'Nocturne.Avalonia', 'Controls', 'NocturneIconKind.g.cs')
OUT_WEB_ENUM = os.path.join(ROOT, 'src', 'Nocturne.Web', 'TagHelpers', 'NocturneIconKind.g.cs')
OUT_SPRITE = os.path.join(ROOT, 'src', 'Nocturne.Web', 'wwwroot', 'img', 'icons.svg')
ICONS_XAML = os.path.join(ROOT, 'src', 'Nocturne.Wpf', 'Styles', 'Icons.xaml')
SVG_NS = '{http://www.w3.org/2000/svg}'
HEADER = '// Generated by tools/generate_icons.py from icons/icons.json; do not edit.\n'


def pascal(mdi):
    """view-grid -> ViewGrid, the name MahApps' PackIconMaterialKind uses."""
    return ''.join(part[:1].upper() + part[1:] for part in mdi.split('-'))


def manifest():
    with open(os.path.join(ICONS, 'icons.json'), encoding='utf-8') as f:
        return json.load(f)


def fetch(data):
    base = f"https://cdn.jsdelivr.net/npm/{data['package']}@{data['version']}/"
    os.makedirs(SVG_DIR, exist_ok=True)
    wanted = [('LICENSE', os.path.join(ICONS, 'LICENSE'))]
    wanted += [(f'svg/{mdi}.svg', os.path.join(SVG_DIR, mdi + '.svg')) for mdi in data['icons']]
    for remote, target in wanted:
        if os.path.exists(target):
            continue
        with urllib.request.urlopen(base + remote, timeout=30) as response:
            content = response.read()
        with open(target, 'wb') as f:
            f.write(content)
        print('fetched', remote)


def path_data(mdi):
    """The d of the single 24x24 path in an MDI file."""
    root = ET.parse(os.path.join(SVG_DIR, mdi + '.svg')).getroot()
    if root.get('viewBox') != '0 0 24 24':
        raise ValueError(f'{mdi}.svg: expected viewBox 0 0 24 24')
    paths = [p.get('d') for p in root.iter(SVG_NS + 'path')]
    if len(paths) != 1:
        raise ValueError(f'{mdi}.svg: expected one path, found {len(paths)}')
    return paths[0]


def enum(data, icons, namespace):
    """The enum plus a lookup from each member to its path data."""
    lines = [HEADER, f'namespace {namespace};', '',
             f"/// <summary>The Nocturne icons: {data['source']}, {data['package']} {data['version']} "
             f"({data['license']}), drawn filled on a 24×24 grid.</summary>",
             'public enum NocturneIconKind', '{', '    None,']
    lines += [f'    {name},' for name in icons]
    lines += ['}', '']
    lines += ['internal static class NocturneIconData', '{',
              '    /// <summary>Path data of an icon in a 24×24 box; empty for None.</summary>',
              '    public static string Get(NocturneIconKind kind) => kind switch', '    {']
    lines += [f'        NocturneIconKind.{name} => "{value}",' for name, value in icons.items()]
    lines += ['        _ => "",', '    };', '}', '']
    return '\n'.join(lines)


def web_enum(data, icons):
    """The enum for the web, with the sprite id (the MDI name) of each member."""
    lines = [HEADER, 'namespace Nocturne.Web.TagHelpers;', '',
             f"/// <summary>The Nocturne icons: {data['source']}, {data['package']} {data['version']} "
             f"({data['license']}), drawn filled on a 24×24 grid.</summary>",
             'public enum NocturneIconKind', '{', '    None,']
    lines += [f'    {pascal(mdi)},' for mdi in icons]
    lines += ['}', '']
    lines += ['internal static class NocturneIconIds', '{',
              '    /// <summary>Id of an icon in icons.svg (its MDI name); empty for None.</summary>',
              '    public static string Get(NocturneIconKind kind) => kind switch', '    {']
    lines += [f'        NocturneIconKind.{pascal(mdi)} => "{mdi}",' for mdi in icons]
    lines += ['        _ => "",', '    };', '}', '']
    return '\n'.join(lines)


def stroke_icons():
    """The line icons of Styles/Icons.xaml (Nocturne.Icons.ChevronDown -> chevron-down), Caption.* left out."""
    root = ET.parse(ICONS_XAML).getroot()
    out = {}
    for el in root:
        key = el.get('{http://schemas.microsoft.com/winfx/2006/xaml}Key') or ''
        name = key.replace('Nocturne.Icons.', '')
        if not key.startswith('Nocturne.Icons.') or name.startswith('Caption.'):
            continue
        out['stroke-' + re.sub(r'(?<=[a-z0-9])(?=[A-Z])', '-', name).lower()] = el.text.strip()
    return out


def sprite(data, icons):
    lines = ['<svg xmlns="http://www.w3.org/2000/svg">',
             f"<!-- Generated by tools/generate_icons.py. {data['source']}, {data['package']} {data['version']}, "
             f"{data['license']}. -->"]
    lines += [f'<symbol id="{mdi}" viewBox="0 0 24 24"><path d="{d}"/></symbol>' for mdi, d in icons.items()]
    lines.append("<!-- The theme's own line icons (Styles/Icons.xaml, MIT); the page sets stroke-width (1.6 as StrokeIcon) -->")
    lines += [f'<symbol id="{name}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-linecap="round" '
              f'stroke-linejoin="round"><path d="{d}"/></symbol>' for name, d in stroke_icons().items()]
    lines.append('</svg>')
    return '\n'.join(lines) + '\n'


def outputs():
    data = manifest()
    names = sorted(data['icons'])
    icons = {pascal(mdi): path_data(mdi) for mdi in names}
    return {OUT_WPF: enum(data, icons, 'Nocturne.Wpf.Controls'),
            OUT_AVALONIA: enum(data, icons, 'Nocturne.Avalonia.Controls'),
            OUT_WEB_ENUM: web_enum(data, names),
            OUT_SPRITE: sprite(data, {mdi: path_data(mdi) for mdi in names})}


def main():
    if '--fetch' in sys.argv:
        fetch(manifest())
    files = outputs()
    if '--check' in sys.argv:
        stale = [p for p, text in files.items()
                 if not os.path.exists(p) or open(p, encoding='utf-8').read() != text]
        if stale:
            print('out of date: ' + ', '.join(os.path.relpath(p, ROOT) for p in stale) + '; run python tools/generate_icons.py')
            sys.exit(1)
        return
    for path, text in files.items():
        os.makedirs(os.path.dirname(path), exist_ok=True)
        # CRLF, as Git checks text files out on Windows (core.autocrlf), so a run leaves no diff
        with open(path, 'w', encoding='utf-8', newline='\r\n') as f:
            f.write(text)
        print('wrote', os.path.relpath(path, ROOT))


if __name__ == '__main__':
    main()
