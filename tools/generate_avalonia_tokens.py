"""Builds Nocturne.Avalonia's design tokens from the WPF library, which stays their source:

    src/Nocturne.Wpf/Styles/Brushes.xaml           -> src/Nocturne.Avalonia/Styles/Brushes.axaml
    src/Nocturne.Wpf/Styles/Icons.xaml             -> src/Nocturne.Avalonia/Styles/Icons.axaml
    src/Nocturne.Wpf/Controls/NocturneTheme.cs     -> src/Nocturne.Avalonia/Controls/NocturneAccent.g.cs
        (the NocturneAccent enum and the accent palettes, copied as they are)

The XAML keeps its keys, values and comments; only what Avalonia spells differently changes: the
namespace, relative gradient points (0,1 -> 0%,100%; Avalonia reads 0,1 as pixels) and Geometry
(StreamGeometry).

Usage (from the repository root):
    python tools/generate_avalonia_tokens.py           write the files
    python tools/generate_avalonia_tokens.py --check   exit with 1 when a file is out of date
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WPF = os.path.join(ROOT, 'src', 'Nocturne.Wpf')
AVALONIA = os.path.join(ROOT, 'src', 'Nocturne.Avalonia')

WPF_NS = 'xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"'
AVALONIA_NS = 'xmlns="https://github.com/avaloniaui"'


def read(path):
    with open(path, encoding='utf-8-sig') as f:
        return f.read().replace('\r\n', '\n')


def xaml_header(source):
    return (f'<!-- Generated by tools/generate_avalonia_tokens.py from {source}; do not edit. '
            f'Change the WPF file and run the script. -->\n')


def percent(value):
    number = float(value) * 100
    return f'{number:g}%'


def relative_points(match):
    x, y = match.group(2).split(',')
    return f'{match.group(1)}="{percent(x.strip())},{percent(y.strip())}"'


def brushes():
    text = read(os.path.join(WPF, 'Styles', 'Brushes.xaml'))
    if WPF_NS not in text:
        raise ValueError('Brushes.xaml: WPF namespace not found')
    text = text.replace(WPF_NS, AVALONIA_NS)
    text = re.sub(r'\b(StartPoint|EndPoint)="([^"%]+)"', relative_points, text)
    return xaml_header('src/Nocturne.Wpf/Styles/Brushes.xaml') + text


def icons():
    text = read(os.path.join(WPF, 'Styles', 'Icons.xaml'))
    if WPF_NS not in text:
        raise ValueError('Icons.xaml: WPF namespace not found')
    text = text.replace(WPF_NS, AVALONIA_NS)
    text = re.sub(r'<Geometry\b', '<StreamGeometry', text)
    text = text.replace('</Geometry>', '</StreamGeometry>')
    return xaml_header('src/Nocturne.Wpf/Styles/Icons.xaml') + text


def accents():
    text = read(os.path.join(WPF, 'Controls', 'NocturneTheme.cs'))
    enum = re.search(r'(/// <summary>The accent colours.*?\npublic enum NocturneAccent\n\{.*?\n\})', text, re.S)
    palettes = re.search(r'\n(    private static readonly Dictionary<NocturneAccent, Palette> Palettes = new\(\)\n    \{.*?\n    \};)', text, re.S)
    if not enum or not palettes:
        raise ValueError('NocturneTheme.cs: the NocturneAccent enum or the Palettes dictionary was not found')
    enum_text = enum.group(1)
    return '\n'.join([
        '// Generated by tools/generate_avalonia_tokens.py from src/Nocturne.Wpf/Controls/NocturneTheme.cs; do not edit.',
        'namespace Nocturne.Avalonia;',
        '',
        enum_text,
        '',
        'public partial class NocturneTheme',
        '{',
        palettes.group(1),
        '}',
        '',
    ])


def outputs():
    return {
        os.path.join(AVALONIA, 'Styles', 'Brushes.axaml'): brushes(),
        os.path.join(AVALONIA, 'Styles', 'Icons.axaml'): icons(),
        os.path.join(AVALONIA, 'Controls', 'NocturneAccent.g.cs'): accents(),
    }


def main():
    files = outputs()
    if '--check' in sys.argv:
        stale = [p for p, text in files.items()
                 if not os.path.exists(p) or read(p) != text]
        if stale:
            print('out of date: ' + ', '.join(os.path.relpath(p, ROOT) for p in stale)
                  + '; run python tools/generate_avalonia_tokens.py')
            sys.exit(1)
        return
    for path, text in files.items():
        os.makedirs(os.path.dirname(path), exist_ok=True)
        # CRLF, as Git checks text files out on Windows (core.autocrlf), so a run leaves no diff
        with open(path, 'w', encoding='utf-8', newline='\r\n') as f:
            f.write(text)
        print('wrote', os.path.relpath(path, ROOT))


if __name__ == '__main__':
    main()
